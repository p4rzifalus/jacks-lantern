// Утро: одна реплика — итог ночи. summary = { scared, lost: { crops: { carrot: 2 }, coins }, faded: ['carrot', ...] }
export function morningLine({ scared, lost, faded }) {
  const crops = Object.entries(lost.crops).filter(([, n]) => n > 0)
    .map(([type, n]) => plural(n, PLANTS[type].forms));
  if (lost.coins) crops.push(plural(lost.coins, ['монету', 'монеты', 'монет']));
  const chased = scared === 1 ? 'одного духа' : plural(scared, ['духа', 'духов', 'духов']);
  const gone = crops.length > 1 ? `${crops.slice(0, -1).join(', ')} и ${crops.at(-1)}` : crops[0];
  let line;
  if (!scared && !crops.length) line = 'Ночь прошла тихо. Даже скучно.';
  else if (!crops.length) line = `Прогнали ${chased} и ничего не отдали. Неплохо для енота с фонарём.`;
  else if (!scared) line = `Унесли ${gone}. В следующий раз встретим как следует.`;
  else line = `Унесли ${gone}. Зато ${chased} прогнали.`;
  if (faded.length) line += ' Кое-что на грядках отслужило своё и засохло — собери, будут семена.';
  return line;
}
